"""Unit tests for CloudPulse AI Machine Learning and Dataset Pipeline.

Verifies:
1. Absence of temporal data leakage in train/test splitting
2. Correct shape, cyclical features, lags, and rolling metrics in preprocessor
3. Proper evaluation metric computation (MAE and RMSE) for RF and Baseline
4. Multi-step forward horizon forecasting (3, 6, 12 steps)
"""

import numpy as np
import pandas as pd
import pytest

from app.ml.generator import generate_synthetic_workload
from app.ml.preprocessor import (
    create_features,
    chronological_train_test_split,
    extract_features_and_targets,
    FEATURE_TARGETS,
    DEFAULT_LAGS,
    DEFAULT_WINDOWS,
)
from app.ml.model import WorkloadForecaster, DummyRegressor


@pytest.fixture(scope="module")
def raw_workload_df():
    """Generate 7-day workload for testing."""
    return generate_synthetic_workload(days=7, interval_minutes=5, seed=42)


def test_synthetic_data_generator_properties(raw_workload_df):
    """Verify synthetic generator output schema, bounds, and reproducibility."""
    expected_cols = {"timestamp", "cpu_usage", "memory_usage", "request_count", "response_time"}
    assert expected_cols.issubset(raw_workload_df.columns)

    # 7 days * 288 steps/day = 2016 steps
    assert len(raw_workload_df) == 2016

    # Verify physical metric bounds
    assert (raw_workload_df["cpu_usage"] >= 0.0).all()
    assert (raw_workload_df["cpu_usage"] <= 100.0).all()
    assert (raw_workload_df["memory_usage"] >= 0.0).all()
    assert (raw_workload_df["memory_usage"] <= 100.0).all()
    assert (raw_workload_df["request_count"] > 0).all()
    assert (raw_workload_df["response_time"] > 0.0).all()

    # Verify strict reproducibility with identical seed
    second_run = generate_synthetic_workload(days=7, interval_minutes=5, seed=42)
    pd.testing.assert_frame_equal(raw_workload_df, second_run)


def test_strict_chronological_split_no_data_leakage(raw_workload_df):
    """Verify test split is strictly forward in time with zero overlap or shuffle."""
    train_df, test_df = chronological_train_test_split(raw_workload_df, train_ratio=0.8)

    # Lengths must sum to total
    assert len(train_df) + len(test_df) == len(raw_workload_df)
    assert len(train_df) == int(len(raw_workload_df) * 0.8)

    # Strict temporal boundary test: max(train) < min(test)
    max_train_ts = train_df["timestamp"].max()
    min_test_ts = test_df["timestamp"].min()

    assert min_test_ts > max_train_ts, (
        f"Data leakage detected! min(test)={min_test_ts} is not > max(train)={max_train_ts}"
    )


def test_preprocessor_features_and_shape(raw_workload_df):
    """Verify lag, rolling, and cyclical features generated by preprocessor."""
    engineered = create_features(raw_workload_df, drop_na=True)

    # Check that initial NaN rows from lag 6 are dropped
    assert not engineered.isna().any().any()
    max_lag = max(DEFAULT_LAGS)
    assert len(engineered) == len(raw_workload_df) - max_lag

    # Verify cyclical features
    for col in ["hour_sin", "hour_cos", "dow_sin", "dow_cos"]:
        assert col in engineered.columns
        assert (engineered[col] >= -1.0).all() and (engineered[col] <= 1.0).all()

    # Verify lags and rolling features for both targets
    for target in FEATURE_TARGETS:
        for lag in DEFAULT_LAGS:
            assert f"{target}_lag_{lag}" in engineered.columns
        for w in DEFAULT_WINDOWS:
            assert f"{target}_roll_mean_{w}" in engineered.columns
            assert f"{target}_roll_std_{w}" in engineered.columns

    # Test extract_features_and_targets
    X, y, feature_names = extract_features_and_targets(engineered)
    assert "timestamp" not in X.columns
    assert "cpu_usage" not in X.columns
    assert "memory_usage" not in X.columns
    assert set(y.columns) == set(FEATURE_TARGETS)
    assert len(X) == len(y) == len(engineered)


def test_dummy_regressor_persistence(raw_workload_df):
    """Verify DummyRegressor persistence strategy reproduces lag_1 or last value."""
    feat_df = create_features(raw_workload_df)
    X, y, _ = extract_features_and_targets(feat_df)

    dummy = DummyRegressor(strategy="last", target_name="cpu_usage")
    dummy.fit(X, y["cpu_usage"])

    preds = dummy.predict(X)
    # Since X has cpu_usage_lag_1, predictions should match cpu_usage_lag_1 exactly
    np.testing.assert_allclose(preds, X["cpu_usage_lag_1"].to_numpy())


def test_forecaster_evaluation_metrics(raw_workload_df):
    """Verify RandomForest and Baseline metrics return valid MAE and RMSE."""
    feat_df = create_features(raw_workload_df)
    train_df, test_df = chronological_train_test_split(feat_df, train_ratio=0.8)

    X_train, y_train, _ = extract_features_and_targets(train_df)
    X_test, y_test, _ = extract_features_and_targets(test_df)

    # Train models with fast configuration for unit testing
    forecaster = WorkloadForecaster(n_estimators=30, random_state=42)
    forecaster.fit(X_train, y_train)

    assert forecaster.is_fitted

    metrics = forecaster.evaluate(X_test, y_test)

    # Structure checks
    assert "cpu" in metrics and "memory" in metrics
    for resource in ["cpu", "memory"]:
        for model_type in ["random_forest", "baseline"]:
            assert "mae" in metrics[resource][model_type]
            assert "rmse" in metrics[resource][model_type]

            mae = metrics[resource][model_type]["mae"]
            rmse = metrics[resource][model_type]["rmse"]

            assert isinstance(mae, float) and mae >= 0.0
            assert isinstance(rmse, float) and rmse >= 0.0
            # By mathematical definition: RMSE >= MAE
            assert rmse >= (mae - 1e-4)


@pytest.mark.parametrize("horizon", [3, 6, 12])
def test_multi_step_forward_inference(raw_workload_df, horizon):
    """Verify multi-step forward inference across horizons 3, 6, and 12 steps."""
    feat_df = create_features(raw_workload_df)
    train_df, test_df = chronological_train_test_split(feat_df, train_ratio=0.8)
    X_train, y_train, _ = extract_features_and_targets(train_df)

    forecaster = WorkloadForecaster(n_estimators=20, random_state=42)
    forecaster.fit(X_train, y_train)

    # Provide 20 most recent rows of test_df
    recent_history = test_df.iloc[-20:].copy()
    last_known_ts = recent_history["timestamp"].iloc[-1]

    forecast = forecaster.predict_multi_step(recent_history, horizon_steps=horizon, interval_minutes=5)

    assert len(forecast) == horizon
    assert list(forecast["step"]) == list(range(1, horizon + 1))
    assert set(forecast.columns) == {"step", "timestamp", "cpu_usage", "memory_usage"}

    # Timestamps should be in the future and strictly increasing by 5 minutes
    first_forecast_ts = forecast["timestamp"].iloc[0]
    assert first_forecast_ts == last_known_ts + pd.Timedelta(minutes=5)
    assert forecast["timestamp"].is_monotonic_increasing

    # Forecast values within 0-100% bounds
    assert (forecast["cpu_usage"] >= 0.0).all() and (forecast["cpu_usage"] <= 100.0).all()
    assert (forecast["memory_usage"] >= 0.0).all() and (forecast["memory_usage"] <= 100.0).all()
