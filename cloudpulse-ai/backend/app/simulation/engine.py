"""Discrete Cloud Resource Simulation Engine for CloudPulse AI.

Simulates discrete step-by-step workload processing, cluster scaling dynamics,
SLA compliance, latency degradation, and operational infrastructure costs.

DISCLAIMER:
All response times, cluster states, and instance telemetry generated by this engine
are synthetic discrete-event simulations for decision-support and planning.
"""

from enum import Enum
import math
from typing import Dict, Any, List, Optional, Sequence
import numpy as np

from app.simulation.instance import VirtualInstance, InstanceStatus
from app.simulation.policies import BaseScalingPolicy, ReactivePolicy, PredictivePolicy


class WorkloadProfile(str, Enum):
    """Preset workload test profiles."""
    NORMAL = "Normal"
    SPIKE = "Spike"
    RAMP_UP = "Ramp-up"
    DROP = "Drop"


def generate_profile_workload(
    profile: str | WorkloadProfile = WorkloadProfile.NORMAL,
    steps: int = 50,
    seed: int = 42,
) -> List[float]:
    """Generate synthetic demand time-series (RPS) for standard workload profiles.

    Args:
        profile: Selected workload profile.
        steps: Total discrete simulation steps.
        seed: Random seed for reproducibility.

    Returns:
        List of incoming demand values in Requests Per Second (RPS).
    """
    rng = np.random.default_rng(seed)
    profile_str = profile.value if isinstance(profile, WorkloadProfile) else str(profile)
    t = np.arange(steps)

    if profile_str.lower() in ("normal", "steady"):
        # Baseline ~500 RPS with diurnal-like sine wave and mild noise
        base = 500.0 + 160.0 * np.sin(2.0 * np.pi * t / 24.0)
        noise = rng.normal(0, 20.0, size=steps)
        demand = np.maximum(50.0, base + noise)

    elif profile_str.lower() in ("spike", "burst"):
        # Steady baseline ~450 RPS with sudden acute burst (1600 RPS) between steps 20 and 26
        demand = 450.0 + rng.normal(0, 15.0, size=steps)
        spike_mask = (t >= 20) & (t <= 26)
        demand[spike_mask] = 1600.0 + rng.normal(0, 30.0, size=np.sum(spike_mask))

    elif profile_str.lower() in ("ramp_up", "ramp-up", "ramp"):
        # Monotonic linear increase from 200 RPS to 1800 RPS
        demand = np.linspace(200.0, 1800.0, steps) + rng.normal(0, 20.0, size=steps)

    elif profile_str.lower() in ("drop", "ramp_down", "crash"):
        # High starting demand (1600 RPS) that suddenly plunges to 250 RPS at step 20
        demand = np.where(t < 20, 1600.0 + rng.normal(0, 25.0, size=steps), 250.0 + rng.normal(0, 15.0, size=steps))

    else:
        # Default fallback
        demand = np.full(steps, 500.0) + rng.normal(0, 20.0, size=steps)

    return [float(round(val, 2)) for val in demand]


class ResourceSimulationEngine:
    """Discrete-event cloud cluster auto-scaling simulator."""

    def __init__(
        self,
        instance_capacity_rps: float = 200.0,
        provision_delay_ticks: int = 1,
        r_base_ms: float = 25.0,
        hourly_cost_per_node: float = 0.05,
        tick_duration_minutes: float = 5.0,
    ):
        self.instance_capacity_rps: float = float(instance_capacity_rps)
        self.provision_delay_ticks: int = int(provision_delay_ticks)
        self.r_base_ms: float = float(r_base_ms)
        self.hourly_cost_per_node: float = float(hourly_cost_per_node)
        self.tick_duration_minutes: float = float(tick_duration_minutes)

    def run(
        self,
        policy: BaseScalingPolicy,
        demand_series: Sequence[float],
        initial_instances: int = 2,
    ) -> Dict[str, Any]:
        """Execute step-by-step discrete simulation.

        Args:
            policy: Scaling policy to evaluate at each step.
            demand_series: List of incoming RPS demands per tick.
            initial_instances: Number of initial active instances.

        Returns:
            Dictionary containing aggregated metrics, cost analysis, and step timeline.
        """
        # Initialize cluster with ACTIVE instances
        instances: List[VirtualInstance] = [
            VirtualInstance(
                capacity_rps=self.instance_capacity_rps,
                status=InstanceStatus.ACTIVE,
                provision_delay_ticks=self.provision_delay_ticks,
            )
            for _ in range(max(1, initial_instances))
        ]

        timeline: List[Dict[str, Any]] = []
        response_times: List[float] = []
        cpu_utilizations: List[float] = []

        sla_violations_count: int = 0
        over_provisioned_node_hours: float = 0.0
        under_provisioned_node_hours: float = 0.0
        total_cost_usd: float = 0.0
        scale_up_actions: int = 0
        scale_down_actions: int = 0

        hours_per_tick = self.tick_duration_minutes / 60.0
        total_steps = len(demand_series)

        for tick in range(total_steps):
            demand = float(demand_series[tick])

            # 1. Advance lifecycle of existing instances
            for inst in instances:
                inst.tick()

            # Clean out terminated instances
            instances = [i for i in instances if i.status != InstanceStatus.TERMINATING]

            # 2. Compute active operational capacity
            active_instances = [i for i in instances if i.is_active]
            num_active = len(active_instances)
            alive_instances = [i for i in instances if i.is_alive]
            num_alive = len(alive_instances)

            total_capacity = num_active * self.instance_capacity_rps

            # 3. Utilization & SLA Checks
            if total_capacity > 0:
                load_ratio = demand / total_capacity
            else:
                load_ratio = 10.0

            # Simulated cluster CPU and Memory utilization percentages
            sim_cpu = float(min(100.0, max(5.0, load_ratio * 100.0)))
            sim_mem = float(min(98.0, max(20.0, 30.0 + load_ratio * 55.0)))
            cpu_utilizations.append(sim_cpu)

            for inst in active_instances:
                inst.update_telemetry(sim_cpu, sim_mem)

            # 4. Latency Calculation (Non-linear queueing degradation model)
            # R_sim = R_base * (1 + max(0, (Demand - Capacity)/Capacity)^2)
            if total_capacity > 0:
                deficit_ratio = max(0.0, (demand - total_capacity) / total_capacity)
                sim_response_time = self.r_base_ms * (1.0 + (deficit_ratio ** 2))
            else:
                sim_response_time = self.r_base_ms * 100.0  # complete outage penalty

            sim_response_time = float(min(5000.0, round(sim_response_time, 2)))
            response_times.append(sim_response_time)

            # 5. SLA Violations & Over/Under-Provisioning
            is_sla_violated = demand > total_capacity
            if is_sla_violated:
                sla_violations_count += 1
                deficit_rps = demand - total_capacity
                under_provisioned_node_hours += (deficit_rps / self.instance_capacity_rps) * hours_per_tick
            else:
                excess_rps = total_capacity - demand
                over_provisioned_node_hours += (excess_rps / self.instance_capacity_rps) * hours_per_tick

            # 6. Cost Accumulation (charged for active and provisioning nodes)
            step_cost = num_alive * self.hourly_cost_per_node * hours_per_tick
            total_cost_usd += step_cost

            # 7. Evaluate Auto-Scaling Policy
            lookahead_forecast = list(demand_series[tick + 1 : tick + 4])
            scaling_delta = policy.evaluate(
                current_tick=tick,
                instances=instances,
                current_cpu=sim_cpu,
                current_memory=sim_mem,
                current_demand=demand,
                forecast_demands=lookahead_forecast,
            )

            action_note = "NONE"
            if scaling_delta > 0:
                scale_up_actions += 1
                action_note = f"SCALE_UP (+{scaling_delta})"
                for _ in range(scaling_delta):
                    instances.append(
                        VirtualInstance(
                            capacity_rps=self.instance_capacity_rps,
                            status=InstanceStatus.PROVISIONING,
                            provision_delay_ticks=self.provision_delay_ticks,
                        )
                    )
            elif scaling_delta < 0:
                scale_down_actions += 1
                to_remove = abs(scaling_delta)
                action_note = f"SCALE_DOWN ({scaling_delta})"
                # Decommission oldest active instances
                for inst in active_instances[:to_remove]:
                    inst.terminate()

            # Record step timeline snapshot
            timeline.append(
                {
                    "tick": tick,
                    "demand_rps": demand,
                    "active_instances": num_active,
                    "total_instances": num_alive,
                    "capacity_rps": round(total_capacity, 2),
                    "cpu_utilization": round(sim_cpu, 2),
                    "memory_utilization": round(sim_mem, 2),
                    "response_time_ms": sim_response_time,
                    "sla_violation": is_sla_violated,
                    "action": action_note,
                    "step_cost_usd": round(step_cost, 5),
                }
            )

        # Final Aggregated Metrics
        p95_latency = float(round(np.percentile(response_times, 95), 2)) if response_times else 0.0
        avg_latency = float(round(float(np.mean(response_times)), 2)) if response_times else 0.0
        avg_cpu = float(round(float(np.mean(cpu_utilizations)), 2)) if cpu_utilizations else 0.0
        sla_rate = float(round((sla_violations_count / total_steps) * 100.0, 2)) if total_steps > 0 else 0.0

        return {
            "policy_name": policy.name,
            "total_ticks": total_steps,
            "sla_violations_count": sla_violations_count,
            "sla_violation_rate_pct": sla_rate,
            "avg_response_time_ms": avg_latency,
            "p95_response_time_ms": p95_latency,
            "avg_cpu_utilization_pct": avg_cpu,
            "over_provisioned_node_hours": round(over_provisioned_node_hours, 3),
            "under_provisioned_node_hours": round(under_provisioned_node_hours, 3),
            "scale_up_actions": scale_up_actions,
            "scale_down_actions": scale_down_actions,
            "total_scaling_actions": scale_up_actions + scale_down_actions,
            "total_cost_usd": round(total_cost_usd, 4),
            "timeline": timeline,
            "disclaimer": (
                "NOTE: All cluster node states, utilization metrics, and latency values "
                "are generated by the CloudPulse discrete-event simulation engine for optimization modeling."
            ),
        }
